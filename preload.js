const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('streamhub', {
  getState: () => ipcRenderer.invoke('state:get'),
  onState: (callback) => ipcRenderer.on('state', (_event, state) => callback(state)),
  refresh: () => ipcRenderer.invoke('modules:refresh'),
  install: (id) => ipcRenderer.invoke('modules:install', id),
  uninstall: (id) => ipcRenderer.invoke('modules:uninstall', id),
  saveModuleSettings: (id, values) => ipcRenderer.invoke('modules:settings', id, values),
  previewModuleSettings: (id, values) => ipcRenderer.invoke('modules:settingsPreview', id, values),
  moduleAction: (id, name) => ipcRenderer.invoke('modules:action', id, name),
  openAccount: () => ipcRenderer.invoke('account:open'),
  pairAccount: (code) => ipcRenderer.invoke('account:pair', code),
  disconnectAccount: () => ipcRenderer.invoke('account:disconnect'),
  connectTwitch: () => ipcRenderer.invoke('twitch:connect'),
  cancelTwitch: () => ipcRenderer.invoke('twitch:cancel'),
  disconnectTwitch: () => ipcRenderer.invoke('twitch:disconnect'),
  openModule: (id) => ipcRenderer.invoke('modules:open', id),
  openSite: () => ipcRenderer.invoke('site:open'),
  openHome: () => ipcRenderer.invoke('site:home'),
  saveSettings: (patch) => ipcRenderer.invoke('settings:save', patch),
  saveKeywords: (list, renames) => ipcRenderer.invoke('keywords:save', list, renames),
  keywordUsage: (name) => ipcRenderer.invoke('keywords:usage', name),
  setModuleIcon: (id, dataUrl) => ipcRenderer.invoke('modules:icon', id, dataUrl),
  setLanguage: (code) => ipcRenderer.invoke('app:language', code),
  i18nExtra: () => ipcRenderer.invoke('app:i18n'),
  pickFile: () => ipcRenderer.invoke('dialog:file'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  setActive: (id, active) => ipcRenderer.invoke('modules:active', id, active),
  installExtension: () => ipcRenderer.invoke('extensions:install'),
  removeExtension: (id) => ipcRenderer.invoke('extensions:remove', id),
  downloadExtension: (id) => ipcRenderer.invoke('extensions:download', id),
  shareList: () => ipcRenderer.invoke('share:list'),
  shareExport: (opts) => ipcRenderer.invoke('share:export', opts),
  shareImport: (dir) => ipcRenderer.invoke('share:import', dir),
  shareOpen: () => ipcRenderer.invoke('share:open'),
  recordInput: (kind) => ipcRenderer.invoke('input:record', kind),
  captureKey: () => ipcRenderer.invoke('keys:capture'),
  saveBackup: () => ipcRenderer.invoke('backup:save'),
  exportBot: () => ipcRenderer.invoke('bot:export'),
  importBot: () => ipcRenderer.invoke('bot:import'),
  loadBackup: () => ipcRenderer.invoke('backup:load'),
});
